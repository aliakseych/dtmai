from dataclasses import dataclass
from datetime import datetime
from typing import Protocol
from uuid import UUID

from app.modules.identity.domain.models import EmailCode, RefreshToken, User


class UserRepository(Protocol):
    async def get(self, user_id: UUID) -> User | None: ...
    async def by_email(self, email: str) -> User | None: ...
    async def by_telegram_id(self, telegram_id: int) -> User | None: ...
    async def add(self, user: User) -> None: ...
    async def save(self, user: User) -> None: ...
    async def search(
        self,
        q: str | None,
        role: str | None,
        disabled: bool | None,
        sort: str,
        descending: bool,
        limit: int,
        offset: int,
    ) -> tuple[int, list[User]]: ...
    async def get_many(self, ids: list[UUID]) -> list[User]: ...
    async def count_active_admins(self) -> int: ...
    async def contacts(
        self, after: UUID | None, limit: int, locale: str | None, with_email: bool
    ) -> list[User]: ...
    async def touch(self, user_id: UUID, now: datetime) -> None: ...
    async def delete_guests_unseen_since(self, cutoff: datetime) -> int: ...
    async def count_by_dream_lyceum(self, lyceum_id: UUID) -> int: ...


class EmailCodeRepository(Protocol):
    async def add(self, code: EmailCode) -> None: ...
    async def latest_for(self, user_id: UUID) -> EmailCode | None: ...
    async def record_attempt(self, code_id: UUID) -> None: ...
    async def consume(self, code_id: UUID) -> None: ...


class RefreshTokenRepository(Protocol):
    async def add(self, token: RefreshToken) -> None: ...
    async def by_hash(self, token_hash: str) -> RefreshToken | None: ...
    async def revoke(self, token_id: UUID) -> None: ...
    async def revoke_all(self, user_id: UUID) -> None: ...


class PasswordHasher(Protocol):
    def hash(self, password: str) -> str: ...
    def verify(self, password: str, hashed: str) -> bool: ...


class Mailer(Protocol):
    async def send(self, to: str, subject: str, body: str) -> None: ...


class Clock(Protocol):
    def now(self) -> datetime: ...


class CityCatalog(Protocol):
    """Known city codes (owned by the lyceums module)."""

    async def exists(self, code: str) -> bool: ...


class FieldCatalog(Protocol):
    """Fields of study (owned by the lyceums module)."""

    async def subjects_for(self, field_code: str) -> list[UUID] | None:
        """Admin-mapped subject ids, or None when the field has no mapping."""
        ...

    async def offered_fields(self, lyceum_ids: list[UUID]) -> dict[UUID, set[str]]:
        """lyceum_id -> field codes offered in its newest imported year."""
        ...


@dataclass(frozen=True, slots=True)
class GoogleProfile:
    sub: str
    email: str
    email_verified: bool
    name: str


class GoogleTokenVerifier(Protocol):
    async def verify(self, id_token: str) -> GoogleProfile:
        """Validate a Google ID token; raises `Unauthorized` when it is invalid."""
        ...
