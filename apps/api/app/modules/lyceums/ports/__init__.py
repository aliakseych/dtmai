from datetime import datetime
from typing import Protocol
from uuid import UUID

from app.modules.lyceums.domain.admission import ContactCard, PlanRow
from app.modules.lyceums.domain.models import (
    ImportRun,
    SourceLanguage,
    SourceLyceum,
    SourceSpeciality,
)
from app.modules.lyceums.domain.profile import CityView
from app.modules.lyceums.domain.rep import Post, PostStatus, RepMembership


class LyceumStatsSource(Protocol):
    """Where admission overview data comes from (swappable adapter)."""

    async def lyceums(self) -> list[SourceLyceum]: ...
    async def languages(self) -> list[SourceLanguage]: ...
    async def specialities(
        self, lyceum_external_id: int, language_external_id: int
    ) -> list[SourceSpeciality]: ...


class ImportSink(Protocol):
    """Write side used by the importer."""

    async def upsert_lyceum(self, item: SourceLyceum) -> UUID: ...
    async def upsert_language(self, item: SourceLanguage) -> UUID: ...
    async def upsert_stat(
        self, *, lyceum_id: UUID, language_id: UUID, year: int, item: SourceSpeciality
    ) -> None: ...


class ImportRunRepository(Protocol):
    async def create(self, year: int, requested_by: UUID | None) -> ImportRun: ...
    async def get(self, run_id: UUID) -> ImportRun | None: ...
    async def save(self, run: ImportRun) -> None: ...
    async def reset_stale(self, older_than: datetime) -> None:
        """Fail pending/running runs created before `older_than` (a crashed worker)."""
        ...

    async def active(self) -> ImportRun | None:
        """A pending/running run, if any; serialises concurrent starters."""
        ...

    async def mark_failed(self, run_id: UUID, error: str) -> None:
        """Persist a failure independently of the (rolled back) work transaction."""
        ...

    async def list(self, limit: int) -> list[ImportRun]: ...


class LyceumProfiles(Protocol):
    async def exists(self, lyceum_id: UUID) -> bool: ...
    async def mark_verified_rep(self, lyceum_id: UUID) -> None: ...
    async def update_fields(self, lyceum_id: UUID, fields: dict[str, object]) -> bool:
        """Set profile columns; False when the lyceum does not exist."""
        ...


class CityRepository(Protocol):
    async def exists(self, code: str) -> bool: ...
    async def list_with_counts(self, locale: str) -> list[CityView]: ...


class MembershipRepository(Protocol):
    async def get(self, user_id: UUID, lyceum_id: UUID) -> RepMembership | None: ...
    async def add(self, membership: RepMembership) -> None: ...
    async def save(self, membership: RepMembership) -> None: ...
    async def delete(self, user_id: UUID, lyceum_id: UUID) -> None: ...
    async def list_pending(self, limit: int) -> list[RepMembership]: ...
    async def count_approved(self, user_id: UUID) -> int: ...


class PostRepository(Protocol):
    async def add(self, post: Post) -> None: ...
    async def get(self, post_id: UUID) -> Post | None: ...
    async def save(self, post: Post) -> None: ...
    async def delete(self, post_id: UUID) -> None: ...
    async def list_for_lyceum(self, lyceum_id: UUID) -> list[Post]: ...
    async def list_published(self, lyceum_id: UUID, limit: int) -> list[Post]: ...
    async def list_by_status(self, status: PostStatus, limit: int) -> list[Post]: ...


class RepRoleGranter(Protocol):
    """Grants the `lyceum_rep` role in the identity module."""

    async def grant_lyceum_rep(self, user_id: UUID) -> None: ...
    async def revoke_lyceum_rep(self, user_id: UUID) -> None: ...
    async def has_lyceum_rep(self, user_id: UUID) -> bool: ...


class Clock(Protocol):
    def now(self) -> datetime: ...


class AdmissionStore(Protocol):
    """Seats, contacts and seed-document matches. `*_seed` writes never touch admin edits."""

    async def lyceum_names(self) -> dict[UUID, str]: ...
    async def matches(self, kind: str) -> dict[int, tuple[UUID | None, str]]: ...
    async def save_match(
        self, kind: str, ref: int, lyceum_id: UUID | None, source: str
    ) -> None: ...
    async def upsert_plan_seed(self, row: PlanRow) -> bool:
        """Insert or refresh a seed row; False when an admin-edited row blocks it."""
        ...

    async def upsert_contact_seed(self, card: ContactCard) -> bool: ...
    async def put_plan_admin(self, row: PlanRow) -> None: ...
    async def delete_plan(
        self, lyceum_id: UUID, year: int, direction_code: str, language_name: str | None
    ) -> str | None:
        """Delete a row; returns its source, or None when there was no such row."""
        ...

    async def tombstone_plan(
        self, lyceum_id: UUID, year: int, direction_code: str, language_name: str | None
    ) -> None:
        """Remember an admin-deleted seed row so the import skips it."""
        ...

    async def is_plan_tombstoned(
        self, lyceum_id: UUID, year: int, direction_code: str, language_name: str | None
    ) -> bool: ...
    async def delete_seed_plan(
        self, lyceum_id: UUID, year: int, keys: list[tuple[str, str | None]]
    ) -> None:
        """Drop source=seed rows of one seed entry (admin rows stay)."""
        ...

    async def delete_seed_contact(self, lyceum_id: UUID) -> None: ...
    async def put_contact_admin(self, card: ContactCard) -> None: ...
    async def plan_for(self, lyceum_ids: list[UUID]) -> list[PlanRow]:
        """Rows of the latest plan year per lyceum."""
        ...

    async def contacts_for(self, lyceum_ids: list[UUID]) -> dict[UUID, ContactCard]: ...
    async def stat_rows(self, lyceum_ids: list[UUID]) -> list[tuple[UUID, int, str, int]]:
        """(lyceum_id, year, speciality_code, applications) from edu.uz stats."""
        ...
